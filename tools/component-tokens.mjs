// Builds dist/tokens.components.css from tokens/component-software/*.json, the
// Tier 3 tokens from the portfolio-components Figma file. Every token aliases a
// @hobbs-og/software token, so the output is var() references only and follows
// the brand and theme the page sets. Same naming as software's tokens.css:
// button/color/solid/background/default → --button-color-solid-background-default.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const dir = join(root, 'tokens/component-software');
const lines = [];
for (const file of readdirSync(dir).filter((f) => f.endsWith('.json')).sort()) {
  const walk = (node, path) => {
    for (const [key, value] of Object.entries(node)) {
      if (value && typeof value === 'object' && '$value' in value) {
        const ref = /^\{(.+)\}$/.exec(value.$value);
        if (!ref) throw new Error(`${[...path, key].join('/')}: expected an alias, got ${value.$value}`);
        lines.push(`  --${[...path, key].join('-')}: var(--${ref[1].replace(/\./g, '-')});`);
      } else walk(value, [...path, key]);
    }
  };
  walk(JSON.parse(readFileSync(join(dir, file), 'utf8')), []);
}
mkdirSync(join(root, 'dist'), { recursive: true });
// Declared wherever a brand or theme can be set, for the same reason software's
// tokens.css does: a custom property resolves its var() on the element it is
// declared on.
writeFileSync(join(root, 'dist/tokens.components.css'), `/* Generated by tools/component-tokens.mjs from tokens/component-software/. Do not edit. */\n\n:root,\n[data-theme],\n[data-brand] {\n${lines.join('\n')}\n}\n`);
console.log(`dist/tokens.components.css: ${lines.length} tokens`);
